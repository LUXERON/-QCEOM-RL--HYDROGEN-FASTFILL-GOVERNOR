//! Emits the golden cross-target test vector for the NOSTD twin: the
//! 25 °C nominal-tank QCH2 fill-map image bytes, plus the hashes the
//! dispenser MCU must reproduce and compare bit for bit.
//!
//! `cargo run --release --bin emit_test_vector > ../<NOSTD>/qemu-m55-harness/src/golden.rs`

use h2_fill_gov::domain_engine;
use h2_fill_gov::fill_env::FillEnv;
use h2_fill_gov::image::{build, fingerprint, table_from_policy, tank_hash, IMAGE_LEN};
use h2_fill_gov::thermo::{TankParams, RESIDUAL_SOC};

fn main() {
    let p = TankParams::nominal(25.0);
    let env = FillEnv::new(&p, RESIDUAL_SOC);
    let (policy, _) = domain_engine().train(&env);
    let table = table_from_policy(&|s| policy.action(s));
    let thash = tank_hash(&p);
    let img = build(0xD152_0042, thash, &table);

    // A second, DIFFERENT tank model — the stale-provenance refusal vector.
    let p_other = TankParams::nominal(35.0);

    println!("// generated by emit_test_vector (hosted, nominal 350 L tank @ 25 degC)");
    println!("// DO NOT EDIT -- regenerate with `cargo run --release --bin emit_test_vector`");
    println!("pub const GOLDEN_IMAGE: [u8; {IMAGE_LEN}] = [");
    for (i, b) in img.iter().enumerate() {
        if i % 16 == 0 {
            print!("    ");
        }
        print!("0x{b:02x},");
        if i % 16 == 15 {
            println!();
        } else {
            print!(" ");
        }
    }
    if img.len() % 16 != 0 {
        println!();
    }
    println!("];");
    println!("pub const GOLDEN_SERIAL: u64 = {:#018x};", 0xD152_0042u64);
    println!("pub const GOLDEN_TANK_HASH: u64 = {thash:#018x};");
    println!("pub const GOLDEN_TANK_HASH_OTHER: u64 = {:#018x};", tank_hash(&p_other));
    println!("pub const GOLDEN_MAP_FP: u64 = {:#018x};", fingerprint(&table));
}
